"""Turn design/mascot/bagel-boys-parts.svg into one SVG per character and the site's
inline art module (components/bagel-boys/art.ts). Run from the project root:

    python3 design/mascot/tools/build-art.py
"""
import re

SRC = "design/mascot/bagel-boys-parts.svg"
svg = open(SRC).read()
head, rest = svg.split('<g id="left">', 1)
left_block = '<g id="left">' + rest.split('<g id="right">')[0]
right_block = '<g id="right">' + rest.split('<g id="right">')[1].replace("</svg>", "")


def one(block, viewbox, who):
    h = head.replace('viewBox="0 0 1665 1050"', f'viewBox="{viewbox}"')
    h = h.replace("Two Men bagel boys,", f"Two Men bagel boy ({who}),")
    return h + block.rstrip() + "\n</svg>\n"


left = one(left_block, "0 0 930 1050", "left, with coffee")
right = one(right_block, "950 0 715 1050", "right, cap backwards")
open("design/mascot/bagel-boy-left.svg", "w").write(left)
open("design/mascot/bagel-boy-right.svg", "w").write(right)


def inline(s):
    # The site styles these from globals.css, so drop the comment and the <style> block
    s = re.sub(r"<!--.*?-->\s*", "", s, flags=re.S)
    s = re.sub(r"<style>.*?</style>\s*", "", s, flags=re.S)
    s = re.sub(r"\s*\n\s*", " ", s).strip()
    return s.replace(
        '<svg xmlns="http://www.w3.org/2000/svg"',
        '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false"',
    )


out = f"""// Generated by design/mascot/tools/build-art.py from design/mascot/bagel-boys-parts.svg
// (traced from the original art and split into parts). Regenerate rather than editing.
// Each part appears twice with the same class: a white backing inside .bb-back and the art
// inside .bb-art. Classes: left-leg-back, left-leg-front, left-body, left-arm-cigarette,
// left-smoke, left-arm-coffee; right-leg-back, right-leg-front, right-body, right-arm-wave.
export const LEFT_SVG = {inline(left)!r};

export const RIGHT_SVG = {inline(right)!r};
"""
open("components/bagel-boys/art.ts", "w").write(out)
print("wrote bagel-boy-left.svg, bagel-boy-right.svg, components/bagel-boys/art.ts")
